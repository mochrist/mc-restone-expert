"""Update flags and tick priorities, mirroring net.minecraft.world.level.block.Block and TickPriority."""

from enum import IntEnum

UPDATE_NEIGHBORS = 1
UPDATE_CLIENTS = 2
UPDATE_INVISIBLE = 4
UPDATE_IMMEDIATE = 8
UPDATE_KNOWN_SHAPE = 16
UPDATE_SUPPRESS_DROPS = 32
UPDATE_MOVE_BY_PISTON = 64
UPDATE_SKIP_SHAPE_UPDATE_ON_WIRE = 128
UPDATE_SKIP_BLOCK_ENTITY_SIDEEFFECTS = 256
UPDATE_SKIP_ON_PLACE = 512
UPDATE_NONE = UPDATE_INVISIBLE
UPDATE_ALL = UPDATE_NEIGHBORS | UPDATE_CLIENTS
UPDATE_ALL_IMMEDIATE = UPDATE_ALL | UPDATE_IMMEDIATE

UPDATE_LIMIT = 512
# Level#maxChainedNeighborUpdates, game rule default (MinecraftServer: 1000000)
MAX_CHAINED_NEIGHBOR_UPDATES = 1_000_000


class TickPriority(IntEnum):
    EXTREMELY_HIGH = -3
    VERY_HIGH = -2
    HIGH = -1
    NORMAL = 0
    LOW = 1
    VERY_LOW = 2
    EXTREMELY_LOW = 3
